#!/usr/bin/env python3
"""Offline upper-only masks and crisp painted edges; no runtime pixel access.
Rebuild after shoe/pose artwork changes. Coordinates are normalized per source.
"""
from pathlib import Path
from collections import deque
import json
import numpy as np
from PIL import Image, ImageFilter, ImageDraw
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/fabrics';OUT.mkdir(exist_ok=True)
paths=list((ROOT/'assets').glob('shoe_*.webp'))+list((ROOT/'assets/angles').glob('*_shade.webp'))+list((ROOT/'assets/poses').glob('*_shade.webp'))+list((ROOT/'assets/legs').glob('leg_*.webp'))
regions={}
for path in paths:
 im=Image.open(path).convert('RGBA');w,h=im.size;a=np.array(im);alpha=im.getchannel('A')
 if path.parent.name=='legs':alpha=Image.open(path.with_name(path.name.replace('leg_','mask_'))).getchannel('A')
 # Find the one/two shoe components on a small analysis grid, never in browser.
 sw=max(1,w//4);sh=max(1,h//4);small=np.array(alpha.resize((sw,sh)))>100;seen=np.zeros_like(small);boxes=[]
 for sy,sx in zip(*np.where(small)):
  if seen[sy,sx]:continue
  q=deque([(sy,sx)]);seen[sy,sx]=True;points=[]
  while q:
   y,x=q.popleft();points.append((x,y))
   for dy,dx in ((-1,0),(1,0),(0,-1),(0,1)):
    ny,nx=y+dy,x+dx
    if 0<=ny<sh and 0<=nx<sw and small[ny,nx] and not seen[ny,nx]:seen[ny,nx]=True;q.append((ny,nx))
  if len(points)>25:
   xx,yy=zip(*points);boxes.append((len(points),max(0,(min(xx)-1)*w/sw),max(0,(min(yy)-1)*h/sh),min(w,(max(xx)+2)*w/sw),min(h,(max(yy)+2)*h/sh)))
 boxes=sorted(boxes,reverse=True)[:2 if path.parent.name in ('angles','poses') else 1]
 regions[path.stem]=[[round(x/w,5),round(y/h,5),round((r-x)/w,5),round((b-y)/h,5)] for _,x,y,r,b in boxes]
 mask=alpha.filter(ImageFilter.MinFilter(5));cut=Image.new('L',im.size);draw=ImageDraw.Draw(cut)
 top='_top_' in path.stem
 for _,x,y,r,b in boxes:
  bw,bh=r-x,b-y
  if top:draw.rectangle((x,y,r,b),fill=255)
  else:
   # Heel sits below the sloping upper. The stepping raised shoe faces right.
   flipped=path.parent.name=='poses' and '_step_' in path.stem and x<w*.5
   polygon=[(0,0),(1,0),(1,.52),(.78,.57),(.57,.86),(.34,.96),(0,.97)]
   draw.polygon([(x+(1-px if flipped else px)*bw,y+py*bh) for px,py in polygon],fill=255)
 pixels=np.array(mask);pixels=np.minimum(pixels,np.array(cut))
 # Preserve warm lining and the thin natural sole on studio sources.
 if path.parent.name=='assets':
  rgb=a[:,:,:3].astype(float);neutral=np.clip((20-(rgb[:,:,0]-rgb[:,:,2]))/8,0,1);pixels=(pixels*neutral).astype('uint8')
 out=np.full_like(a,255);out[:,:,3]=pixels;Image.fromarray(out).save(OUT/(path.stem+'_upper.webp'),lossless=True)
 # Original painted edge, composited last: thin contact lining + luminous piping.
 edge=np.array(alpha).astype(float)-np.array(alpha.filter(ImageFilter.MinFilter(5))).astype(float)
 out=a.copy();out[:,:,3]=np.uint8(np.clip(edge*.8,0,255));Image.fromarray(out).save(OUT/(path.stem+'_edge.webp'),lossless=True)
(ROOT/'js/fabric-regions.js').write_text("'use strict';\n// Generated by dev/build-fabric-assets.py.\nglobalThis.SweetShoe.FABRIC_REGIONS="+json.dumps(regions,separators=(',',':'))+';\n')
print('Built',len(paths)*2,'fabric masks/edges and',len(regions),'source regions')
