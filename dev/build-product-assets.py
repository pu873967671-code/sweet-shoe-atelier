#!/usr/bin/env python3
"""Offline three-stop ramp weights and ankle-height crops; no runtime pixel reads."""
from pathlib import Path
import argparse, json
from PIL import ImageChops, ImageFilter, ImageDraw
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--contacts-only',action='store_true',help='Preserve the accepted colour weights; rebuild floor contacts only')
args=parser.parse_args()
files=list((ROOT/'assets').glob('shoe_*.webp'))+list((ROOT/'assets/angles').glob('*_shade.webp'))+list((ROOT/'assets/poses').glob('*_shade.webp'))+list((ROOT/'assets/legs').glob('leg_*.webp'))
frames={}
contacts={}
levels={}
for path in files:
 im=Image.open(path).convert('RGBA');lum=im.convert('RGB').convert('L',matrix=(.2126,.7152,.0722,0));alpha=im.getchannel('A')
 if path.parent.name=='legs':alpha=Image.open(path.with_name(path.name.replace('leg_','mask_'))).convert('RGBA').getchannel('A')
 # Neutral source paintings cluster near white. Reserve white for their top
 # luminance quintile; the broad 50–80% interval is exactly the selected swatch.
 histogram=lum.histogram(mask=alpha.point(lambda v:255 if v>200 else 0))
 total=sum(histogram)
 def percentile(q):
  count=0
  for value,n in enumerate(histogram):
   count+=n
   if count>=total*q:return value
 low,mid,high,peak=[percentile(q) for q in [.03,.50,.80,.995]]
 levels[path.stem]=[low,mid,high,peak]
 weights={'shadow':lum.point(lambda v:round(max(0,min(1,(mid-v)/max(1,mid-low)))*255)),
          'highlight':lum.point(lambda v:round(max(0,min(1,(v-high)/max(28,peak-high)))*255))}
 for suffix,weight in ([] if args.contacts_only else weights.items()):
  from PIL import ImageChops
  pixels=Image.new('RGBA',im.size,'white');pixels.putalpha(ImageChops.multiply(alpha,weight));pixels.thumbnail((512,512),Image.Resampling.LANCZOS);pixels.save(ROOT/'assets/tones'/f'{path.stem}_{suffix}.webp',lossless=True,method=0)
 for suffix in ['tone','gleam']:
  old=ROOT/'assets/tones'/f'{path.stem}_{suffix}.webp'
  if old.exists() and not args.contacts_only:
   detail=Image.open(old);detail.thumbnail((512,512),Image.Resampling.LANCZOS);detail.save(old,lossless=True,method=0)
 if path.parent.name in ['poses','angles']:
  x0,y0,x1,y1=alpha.point(lambda v:255 if v>100 else 0).getbbox();sh=y1-y0
  top=max(0,int(y0-sh*.5));bottom=min(im.height,int(y1+sh*.12));left=max(0,int(x0-(x1-x0)*.1));right=min(im.width,int(x1+(x1-x0)*.1))
  name=path.stem.removesuffix('_shade')
  frames[name]=[left,top,right-left,bottom-top]
  # Follow the actual opaque outsole, including its perspective, rather than
  # estimating its height from an upper-mask bounding rectangle.
  legs=Image.open(path.with_name(name+'_legs.webp')).convert('RGBA').getchannel('A')
  shoe=alpha.point(lambda v:255 if v>200 else 0);sp=shoe.load();lp=legs.load()
  core=Image.new('L',im.size);draw=ImageDraw.Draw(core)
  pool=Image.new('L',im.size);ambient=ImageDraw.Draw(pool);segments=[]
  # A source-aligned occlusion ribbon has a visible soft footprint, rather
  # than a one-pixel outline. Radius scales with the authored product crop.
  radius=max(8,(bottom-top)*.021)
  profile=[]
  for xx in range(im.width):
   bottom=next((yy for yy in range(im.height-1,-1,-1) if sp[xx,yy]),None)
   if bottom is None:continue
   # Original soles extend a few pixels beyond the recolour mask.
   for yy in range(bottom+1,min(im.height,bottom+13)):
    if lp[xx,yy]>200:bottom=yy
   draw.line((xx,max(0,bottom-2),xx,min(im.height-1,bottom+5)),fill=115)
   ambient.line((xx,max(0,round(bottom-radius*1.5)),xx,min(im.height-1,round(bottom+radius*.85))),fill=110)
   profile.append((xx,bottom))
   if xx%6==0:segments.append([xx,bottom])
  # The heel stem is a narrow low point separated from the broad forefoot.
  # Give each such local minimum a round contact, including crossed poses.
  tips=Image.new('L',im.size);tipdraw=ImageDraw.Draw(tips)
  for xx,yy in profile:
   neighbours=[p for p in profile if abs(p[0]-xx)<=radius*1.5]
   if yy<max(p[1] for p in neighbours)-2:continue
   low=[p for p in neighbours if p[1]>=yy-radius*.5]
   if max(p[0] for p in low)-min(p[0] for p in low)>radius*1.4:continue
   tipdraw.ellipse((xx-radius*.75,yy-radius*.5,xx+radius*.75,yy+radius*.5),fill=115)
  soft=pool.filter(ImageFilter.GaussianBlur(radius))
  soft=ImageChops.lighter(soft,tips.filter(ImageFilter.GaussianBlur(radius*.35)))
  shadow=Image.new('RGBA',im.size,(90,48,40,0));shadow.putalpha(ImageChops.lighter(core.filter(ImageFilter.GaussianBlur(.7)),soft))
  shadow.save(ROOT/'assets/tones'/f'{name}_contact.webp',lossless=True,method=0)
  contacts[name]=segments
(ROOT/'js/product-frames.js').write_text("'use strict';\n// Generated by dev/build-product-assets.py: source-pixel ankle-height crops.\nSweetShoe.PRODUCT_FRAMES="+json.dumps(frames,separators=(',',':'))+';\nSweetShoe.PRODUCT_CONTACTS='+json.dumps(contacts,separators=(',',':'))+';\nSweetShoe.PRODUCT_LEVELS='+json.dumps(levels,separators=(',',':'))+';\n')
print('Built ramp masks and',len(frames),'product crops')
